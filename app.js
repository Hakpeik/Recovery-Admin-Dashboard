function overdueBranchRows(snapshots){
  const rows = new Map();
  for(const snapshot of snapshots){
    for(const [rawName, value] of Object.entries(snapshot.branches || {})){
      const name = overdueBranchCanonical(rawName);
      if(!rows.has(name)) rows.set(name, {branch:name, accounts:0, osUSD:0, overdueUSD:0, classes:{}});
      const item = rows.get(name);
      item.accounts += Number(value.accounts) || 0;
      item.osUSD += Number(value.osUSD) || 0;
      item.overdueUSD += Number(value.overdueUSD) || 0;
      for(const [className, classValue] of Object.entries(value.classes || {})){
        if(!item.classes[className]) item.classes[className] = {accounts:0, osUSD:0};
        item.classes[className].accounts += Number(classValue.accounts) || 0;
        item.classes[className].osUSD += Number(classValue.osUSD) || 0;
      }
    }
  }
  return [...rows.values()].sort((a, b) => b.osUSD - a.osUSD || a.branch.localeCompare(b.branch));
}

