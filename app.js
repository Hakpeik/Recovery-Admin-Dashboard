function overdueBranchCanonical(name){
  const text = String(name || '').toUpperCase().replace(/\s+/g, ' ').trim();
  const code = (text.match(/^KH\d+/) || [''])[0];
  const raw = (text.replace(/^KH\d+\s*[-–]?\s*/, '').trim()
    || OVERDUE_BRANCH_CODES[code]
    || '').trim();
  const short = raw.replace(/\s*BRANCH$/, '').trim();
  return OVERDUE_BRANCH_ALIASES[raw] || OVERDUE_BRANCH_ALIASES[short] || raw || 'UNASSIGNED';
}

function overdueBranchLookup(branches, canonical){
  const total = {accounts:0, osUSD:0, overdueUSD:0, classes:{}};
  for(const [name, value] of Object.entries(branches || {})){
    if(overdueBranchCanonical(name) !== canonical) continue;
    total.accounts += Number(value.accounts) || 0;
    total.osUSD += Number(value.osUSD) || 0;
    total.overdueUSD += Number(value.overdueUSD) || 0;
    for(const [className, classValue] of Object.entries(value.classes || {})){
      if(!total.classes[className]) total.classes[className] = {accounts:0, osUSD:0};
      total.classes[className].accounts += Number(classValue.accounts) || 0;
      total.classes[className].osUSD += Number(classValue.osUSD) || 0;
    }
  }
  return total;
}

