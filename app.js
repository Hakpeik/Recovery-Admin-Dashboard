function reloadData(manual=false){
  if(REFRESHING) return;
  REFRESHING = true;
  const previous = DATA ? DATA.generatedAt : null;
  const script = document.createElement('script');
  let retried = false;
  script.dataset.live = '1';
  script.src = `data.js?t=${Date.now()}`;
  const finish = () => { REFRESHING = false; };
  script.onload = () => {
    finish();
    // Keep only the newest dynamically loaded copy of data.js.
    document.querySelectorAll('script[data-live]').forEach(node => { if(node !== script) node.remove(); });
    const next = window.DASHBOARD_DATA;
    if(!next || !next.generatedAt){ if(manual) toast('data.js did not contain dashboard data'); return; }
    const changed = next.generatedAt !== previous;
    DATA = next;
    if(changed){
      updateStamps();
      renderPage(state.page);
      if(manual) toast('Dashboard refreshed');
    } else if(manual){
      toast('Already up to date');
    }
  };
  script.onerror = () => {
    if(!retried){
      retried = true;
      script.src = 'data.js';
      return;
    }
    finish();
    if(manual) toast('Could not reload data.js — press F5 to refresh');
  };
  document.body.appendChild(script);
}

