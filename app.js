const CONSOL_RESULT_ORDER = ['Promise to pay','Repromise','No Result','N/A','Paid Already'];

function consolidateSelected(){
  const summaries = (DATA.consolidate && DATA.consolidate.summaries) || [];
  if(!summaries.length) return null;
  const end = state.cons.date || '9999-12-31';
  let chosen = null;
  for(const item of summaries){
    if(item.date && item.date <= end && (!chosen || item.date > chosen.date)) chosen = item;
  }
  return chosen || summaries[summaries.length - 1];
}

