function topValues(index){
  const totals = new Map();
  for(const row of DATA.loan.rows){
    const key = row[index];
    if(!key) continue;
    totals.set(key, (totals.get(key) || 0) + (Number(row[LI.os]) || 0));
  }
  return [...totals.entries()].sort((a, b) => b[1] - a[1]).map(([key]) => key);
}

