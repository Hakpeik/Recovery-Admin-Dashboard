function aggregateLoan(rows){
  const result = {
    accounts: rows.length, os: 0, remaining: 0, monthly: 0, osStage3: 0, accountsStage3: 0,
    securedOS: 0, unsecuredOS: 0, stages: new Map(), sectors: new Map(), credits: new Map(), security: new Map()
  };
  const bucket = (map, key) => {
    const name = key || 'Unclassified';
    if(!map.has(name)) map.set(name, {accounts:0, os:0, remaining:0, monthly:0});
    return map.get(name);
  };
  for(const row of rows){
    const os = Number(row[LI.os]) || 0;
    const remaining = Number(row[LI.remaining]) || 0;
    const monthly = Number(row[LI.monthly]) || 0;
    result.os += os;
    result.remaining += remaining;
    result.monthly += monthly;
    if(row[LI.stage] === 'Stage 3'){ result.osStage3 += os; result.accountsStage3 += 1; }
    if(String(row[LI.secured] || '').startsWith('Secure')) result.securedOS += os;
    else result.unsecuredOS += os;

    for(const [map, key] of [[result.stages, row[LI.stage]], [result.sectors, row[LI.sectorRw]], [result.credits, row[LI.credit]], [result.security, row[LI.secured]]]){
      const item = bucket(map, key);
      item.accounts += 1;
      item.os += os;
      item.remaining += remaining;
      item.monthly += monthly;
    }
  }
  return result;
}

