function boot(){
  state.loan.rate = (DATA && DATA.rateKhrPerUsd) || 4055;
  const rateInput = $('#loanRate');
  if(rateInput) rateInput.value = state.loan.rate;
  const baseRate = (DATA && DATA.rateKhrPerUsd) || 4055;
  state.od.rate = baseRate;
  state.cons.rate = baseRate;
  state.npl.rate = baseRate;
  state.month.rate = baseRate;
  state.internal.rate = baseRate;
  if($('#odRate')) $('#odRate').value = state.od.rate;
  if($('#consRate')) $('#consRate').value = state.cons.rate;
  if($('#nplRate')) $('#nplRate').value = state.npl.rate;
  if($('#monthRate')) $('#monthRate').value = state.month.rate;
  if($('#internalRate')) $('#internalRate').value = state.internal.rate;
  bindEvents();
  updateStamps();
  const initial = location.hash.replace('#', '');
  setPage(PAGE_LABELS[initial] ? initial : 'overview', false);
  if(DATA && DATA.loan) initLoan();
}

