function esc(value){
  return String(value ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
}
function nf(value, digits=2){
  return (Number(value) || 0).toLocaleString('en-US', {minimumFractionDigits:digits, maximumFractionDigits:digits});
}
function nf0(value){ return Math.round(Number(value) || 0).toLocaleString('en-US'); }
function pctf(value, digits=1){ return `${(Number(value) || 0).toFixed(digits)}%`; }
function signed(value, digits=2){
  const v = Number(value) || 0;
  return `${v > 0 ? '+' : v < 0 ? '−' : ''}${nf(Math.abs(v), digits)}`;
}
function clamp(v, min, max){ return Math.min(max, Math.max(min, v)); }
function sumBy(list, fn){ return list.reduce((total, item) => total + (Number(fn(item)) || 0), 0); }
function debounce(fn, wait=150){
  let timer = null;
  return (...args) => { clearTimeout(timer); timer = setTimeout(() => fn(...args), wait); };
}
